// Generate src/i18n/strings-index.ts — a static, build-agnostic replacement for
// Vite's `import.meta.glob`. Walks src/i18n/strings/*.json and emits a module
// that imports every locale table and exposes them as a `{ code: table }` map.
//
// Run automatically by `prebuild` / `build`; safe to re-run (idempotent).

import { readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const stringsDir = join(__dirname, '..', 'src', 'i18n', 'strings');
const outFile = join(__dirname, '..', 'src', 'i18n', 'strings-index.ts');

const files = readdirSync(stringsDir)
  .filter((f) => f.endsWith('.json'))
  .sort();

const imports = [];
const entries = [];
files.forEach((file, i) => {
  const code = file.replace(/\.json$/, '');
  const ident = `loc${i}`;
  imports.push(`import ${ident} from './strings/${file}';`);
  entries.push(`  ${JSON.stringify(code)}: ${ident} as RawTable,`);
});

const banner = `// AUTO-GENERATED by scripts/gen-strings-index.mjs — do not edit by hand.
// Static import map of every bundled locale table (${files.length} locales).
/* eslint-disable */
`;

const body = `${banner}
export type RawTable = Record<string, unknown>;

${imports.join('\n')}

export const RAW_STRINGS: Record<string, RawTable> = {
${entries.join('\n')}
};
`;

writeFileSync(outFile, body, 'utf8');
console.log(`[gen-strings-index] wrote ${files.length} locales -> ${outFile}`);
